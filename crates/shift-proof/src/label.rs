//! A 5×7 bitmap face for labels in raster proofs: sizes, locations, and
//! glyph names.
//!
//! Labels must not depend on the font being proofed, which may not draw
//! Latin yet, and the proof carries no UI font. The face covers ASCII
//! letters, digits, and the punctuation glyph names and locations use;
//! anything else draws as `?`.

use crate::numeric::whole_count;

/// Bitmap cells per character, horizontally including the gap.
const CELLS_ACROSS: f32 = 6.0;
/// Bitmap cells per character, vertically.
const CELLS_DOWN: f32 = 7.0;

/// Width of `text` in pixels at `pixel` pixels per cell.
pub(crate) fn label_width(text: &str, pixel: f32) -> f32 {
    text.chars().count() as f32 * CELLS_ACROSS * pixel
}

/// Horizontal distance between characters in pixels at `pixel` pixels per
/// cell.
pub(crate) fn char_advance(pixel: f32) -> f32 {
    CELLS_ACROSS * pixel
}

/// Height of a label line in pixels at `pixel` pixels per cell.
pub(crate) fn label_height(pixel: f32) -> f32 {
    CELLS_DOWN * pixel
}

/// Longest prefix of `text` that fits `width` pixels at `pixel` pixels per
/// cell.
pub(crate) fn fit_label(text: &str, pixel: f32, width: f32) -> String {
    let fits = whole_count(width / (CELLS_ACROSS * pixel));
    text.chars().take(fits).collect()
}

/// Filled cells of `character` as `(column, row)` pairs, row 0 on top.
pub(crate) fn cells(character: char) -> impl Iterator<Item = (u8, u8)> {
    let rows = bitmap(character);
    (0..7u8).flat_map(move |row| {
        (0..5u8)
            .filter(move |column| rows[usize::from(row)] & (0b10000 >> column) != 0)
            .map(move |column| (column, row))
    })
}


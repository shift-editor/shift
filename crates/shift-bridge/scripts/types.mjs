// Writes index.d.ts, napi's declarations of what stays a napi export, and
// protocol.ts, the TypeScript side of the native workspace's
// #[pack::interface] traits, without building the addon. Both macros write
// their descriptions while they expand, which `cargo check` does in seconds;
// the release build behind `napi build` costs most of a minute. index.d.ts
// is the same one `napi build` writes.
//
// The check uses its own target directory: the macros write only when
// NAPI_TYPE_DEF_TMP_FOLDER and PACK_TS_DIR are set, so a check without them
// in a shared directory would leave a crate up to date with nothing written.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { generateTypeDef } from "@napi-rs/cli";
import { generate } from "@shift/pack/generate";
import { cargo, withLock } from "../../../scripts/target-lock.mjs";

const crate = resolve(import.meta.dirname, "..");
const root = resolve(crate, "../..");
const targetDir = join(root, "target", "napi-types");
const typeDefDir = join(targetDir, "type-defs");
const fragments = join(targetDir, "pack-fragments");
/** The napi config `napi build` reads, so both write the same index.d.ts. */
const napiConfig = JSON.parse(readFileSync(join(crate, "package.json"), "utf8")).napi;
/** Crates whose `#[napi]` items reach index.d.ts. */
const napiCrates = ["shift-bridge", "shift-wire"];
/** Crates whose `#[derive(Pack)]` and `#[pack::interface]` items reach protocol.ts. */
const packCrates = ["shift-font", "shift-engine", "shift-wire", "shift-bridge"];

const HEADER = `// Generated by crates/shift-bridge/scripts/types.mjs from the #[derive(Pack)]
// and #[pack::interface] items in shift-bridge, shift-wire, shift-engine and
// shift-font. Not committed; \`pnpm generate:bridge-types\` writes it again.
`;

mkdirSync(typeDefDir, { recursive: true });
mkdirSync(fragments, { recursive: true });
const check = (args) =>
  cargo([...args, "--target-dir", targetDir], {
    cwd: root,
    env: { ...process.env, NAPI_TYPE_DEF_TMP_FOLDER: typeDefDir, PACK_TS_DIR: fragments },
  });
// Other checkouts sharing target/ check into the same directory, so the
// check and the read of its definitions and fragments hold one lock.
await withLock(join(root, "target"), "napi-types", async () => {
  // A crate that is up to date but has no definitions would contribute
  // nothing; clean it so the check expands its macros again.
  const missing = new Set([
    ...napiCrates.filter((name) => !existsSync(join(typeDefDir, name))),
    ...packCrates.filter((name) => !existsSync(join(fragments, name))),
  ]);
  if (missing.size > 0) await check(["clean", ...[...missing].flatMap((name) => ["-p", name])]);
  await check(["check", "-p", "shift-bridge"]);

  const { dts } = await generateTypeDef({
    typeDefDir,
    configDtsHeaderFile: "dts-header.d.ts",
    constEnum: napiConfig.constEnum,
    cwd: crate,
  });
  writeFileSync(join(crate, "index.d.ts"), dts);
  // Imported by @shift/types, which declares the id brands, from its bridge folder.
  generate(fragments, join(crate, "protocol.ts"), HEADER, {
    brandModules: { "@shift/types": "../ids" },
    crates: ["shift-bridge"],
  });
});

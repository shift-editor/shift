// What types.mjs and build.mjs share: the crates whose `#[derive(Pack)]` and
// `#[pack::interface]` items reach protocol.ts, and how their fragments
// become it.
import { existsSync } from "node:fs";
import { join, resolve } from "node:path";
import { generate } from "@shift/pack/generate";

const crate = resolve(import.meta.dirname, "..");

/** Crates whose `#[derive(Pack)]` and `#[pack::interface]` items reach protocol.ts. */
export const packCrates = ["shift-font", "shift-engine", "shift-wire", "shift-bridge"];

const HEADER = `// Generated by crates/shift-bridge/scripts/types.mjs or build.mjs from the
// #[derive(Pack)] and #[pack::interface] items in shift-bridge, shift-wire,
// shift-engine and shift-font. Not committed; \`pnpm generate:bridge-types\` writes it again.
`;

/** The crates in `packCrates` with no folder of fragments in `fragments`. */
export function missingFragments(fragments) {
  return packCrates.filter((name) => !existsSync(join(fragments, name)));
}

/** Writes protocol.ts beside index.d.ts from the fragments in `fragments`. */
export function writeProtocol(fragments) {
  // Imported by @shift/types, which declares the id brands, from its bridge folder.
  generate(fragments, join(crate, "protocol.ts"), HEADER, {
    brandModules: { "@shift/types": "../ids" },
    crates: ["shift-bridge"],
  });
}

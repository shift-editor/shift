//! Checked-in files generated from Rust definitions.
//!
//! A generator is an ordinary `#[test]` that renders a file from the Rust
//! constants it describes and passes it to [`assert_generated_file`]. The test
//! fails when the checked-in copy differs, so changing a Rust definition
//! without regenerating its consumers fails `cargo test`. Running the tests
//! with [`UPDATE_GENERATED_ENV`] set rewrites the files instead.
//!
//! Every generator test's name starts with `generated_file_`: `pnpm
//! generate:from-rust` runs the `shift-font` and `shift-slug` library tests
//! filtered on that prefix, so a generator named otherwise, or living in
//! another crate, is never regenerated by the script.

use std::fmt::Write as _;
use std::path::Path;

/// Environment variable that rewrites generated files instead of comparing them.
pub const UPDATE_GENERATED_ENV: &str = "SHIFT_UPDATE_FIXTURES";

/// Compares a checked-in generated file with freshly generated contents.
///
/// `repo_path` is relative to the repository root. When
/// [`UPDATE_GENERATED_ENV`] is set the file is written instead of compared.
///
/// # Panics
///
/// Panics when the checked-in file differs from `contents`, or when the file
/// cannot be read or written.
#[track_caller]
pub fn assert_generated_file(repo_path: &str, contents: &str) {
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join(repo_path);
    if std::env::var_os(UPDATE_GENERATED_ENV).is_some() {
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).unwrap();
        }
        std::fs::write(&path, contents).unwrap();
        return;
    }

    let checked_in = std::fs::read_to_string(&path)
        .unwrap_or_else(|error| panic!("cannot read generated file {repo_path}: {error}"));
    assert!(
        checked_in == contents,
        "{repo_path} is out of date with its Rust definition; run `pnpm generate:from-rust`\n\
         --- checked in\n{checked_in}\n--- generated\n{contents}"
    );
}

/// Builder for a generated TypeScript module of numeric constants.
///
/// Output follows the repository's Oxfmt style so generated files read like
/// hand-formatted source.
pub struct TypeScriptModule {
    source: String,
}

impl TypeScriptModule {
    /// Starts a module whose header names the Rust file that generates it.
    pub fn new(generator: &str) -> Self {
        Self {
            source: format!(
                "// This file is generated from {generator}.\n\
                 // Run `pnpm generate:from-rust` after changing the Rust definition.\n\
                 // Do not edit this file manually.\n"
            ),
        }
    }

    /// Adds `export const name = value;` with a one-line JSDoc summary.
    pub fn number(mut self, doc: &str, name: &str, value: usize) -> Self {
        write!(
            self.source,
            "\n/** {doc} */\nexport const {name} = {value};\n"
        )
        .unwrap();
        self
    }

    /// Adds a `u32` constant written as eight hexadecimal digits.
    pub fn hex(mut self, doc: &str, name: &str, value: u32) -> Self {
        write!(
            self.source,
            "\n/** {doc} */\nexport const {name} = 0x{value:08x};\n"
        )
        .unwrap();
        self
    }

    /// Adds a readonly object mapping camelCase field names to numeric indices.
    pub fn indices(mut self, doc: &str, name: &str, fields: &[(&str, usize)]) -> Self {
        write!(self.source, "\n/** {doc} */\nexport const {name} = {{\n").unwrap();
        for (field, index) in fields {
            writeln!(self.source, "  {field}: {index},").unwrap();
        }
        self.source.push_str("} as const;\n");
        self
    }

    /// Returns the module source.
    pub fn finish(self) -> String {
        self.source
    }
}

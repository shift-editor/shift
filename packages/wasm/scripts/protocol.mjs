// Writes src/generated-protocol/index.ts, the editor's side of shift-wasm's
// #[pack::interface] traits, and of shift-engine's StoreReader, which the
// engine asks in Rust and tests ask from TypeScript: a class per trait and
// every type they carry.
// Not committed: the build writes it before anything imports it, as it does
// the modules themselves.
//
// The pack macros write a fragment per item while they expand, which a
// `cargo check` does in seconds, but only when PACK_TS_DIR is set. The check
// uses its own target directory, so a crate that is up to date there has
// already written its fragments; a crate whose fragments are missing is
// cleaned so its macros expand again (crates/shift-bridge/scripts/types.mjs
// does the same for napi's type definitions).
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { generate } from "@shift/pack/generate";
import { cargo, withLock } from "../../../scripts/target-lock.mjs";

const root = resolve(import.meta.dirname, "../../..");
const output = resolve(import.meta.dirname, "../src/generated-protocol/index.ts");
const targetDir = join(root, "target", "pack-types");
const fragments = join(targetDir, "fragments");
/** Packages with `#[derive(Pack)]` or `#[pack::interface]` items the module declares. */
const packed = ["shift-font", "shift-text", "shift-engine", "shift-wire", "shift-wasm"];

const HEADER = `// Generated by packages/wasm/scripts/protocol.mjs from the #[derive(Pack)]
// and #[pack::interface] items in shift-wasm, shift-engine, shift-wire and
// shift-font. Not committed; \`pnpm --filter @shift/wasm types\` writes it again.
`;

/** Checks shift-wasm and shift-engine with the pack macros writing fragments, and generates the module from them. */
export function writeProtocol() {
  // Other checkouts sharing target/ check into the same directory, so the
  // check and the read of its fragments hold one lock.
  return withLock(join(root, "target"), "pack-types", checkAndGenerate);
}

/** The check that expands the engine's interfaces, which only `engine-protocol` declares. */
const PROTOCOL_CHECK = [
  "check",
  "-p",
  "shift-wasm",
  "-p",
  "shift-engine",
  "--features",
  "shift-wasm/engine-protocol",
];

async function checkAndGenerate() {
  mkdirSync(fragments, { recursive: true });
  const check = (args) =>
    cargo([...args, "--target-dir", targetDir], {
      cwd: root,
      env: { ...process.env, PACK_TS_DIR: fragments },
    });
  const missing = packed.filter((name) => !existsSync(join(fragments, name)));
  if (missing.length > 0) await check(["clean", ...missing.flatMap((name) => ["-p", name])]);
  await check(PROTOCOL_CHECK);
  // A crate checked without its fragments being written (or since rewritten
  // by another checkout sharing this target directory) has fragments older
  // than its last check. Expand its macros again rather than trust them.
  const stale = packed.filter((name) => newestFragment(name) < lastCheck(name) - STALE_MS);
  if (stale.length > 0) {
    await check(["clean", ...stale.flatMap((name) => ["-p", name])]);
    await check(PROTOCOL_CHECK);
  }
  generate(fragments, output, HEADER);
  assertRenamesApplied();
}

/**
 * A crate's macros write its fragments while it compiles, so they are at most
 * one compile older than its .rmeta. Allow for the slowest one.
 */
const STALE_MS = 60_000;

/** When `name`'s fragments were last written, in ms since the epoch (0 when it has none). */
function newestFragment(name) {
  const folder = join(fragments, name);
  if (!existsSync(folder)) return 0;
  return Math.max(0, ...readdirSync(folder).map((file) => statSync(join(folder, file)).mtimeMs));
}

/** When `name` was last checked in the target directory, in ms since the epoch. */
function lastCheck(name) {
  const deps = join(targetDir, "debug", "deps");
  const prefix = `lib${name.replaceAll("-", "_")}-`;
  const metadata = readdirSync(deps).filter(
    (file) => file.startsWith(prefix) && file.endsWith(".rmeta"),
  );
  return Math.max(0, ...metadata.map((file) => statSync(join(deps, file)).mtimeMs));
}

/** `#[pack(rename = "Name")]` followed, after any other attributes, by the item it renames. */
const RENAME =
  /pack\(rename\s*=\s*"(\w+)"\)\)?\]\s*(?:#\[[^\]]*\]\s*)*pub(?:\([^)]*\))?\s+(?:struct|enum)\s+(\w+)/g;

/**
 * Fails when a type that `#[pack(rename = …)]` renames appears in the module
 * under its Rust name. A stale fragment produces that, and it typechecks. The
 * renames are read from the source, since a stale fragment has lost them.
 */
function assertRenamesApplied() {
  const module = readFileSync(output, "utf8");
  for (const crate of packed) {
    for (const file of readdirSync(join(root, "crates", crate, "src"), { recursive: true })) {
      if (!file.endsWith(".rs")) continue;
      const source = readFileSync(join(root, "crates", crate, "src", file), "utf8");
      for (const [, name, rust] of source.matchAll(RENAME)) {
        if (
          module.includes(`export const ${rust}Schema =`) &&
          !module.includes(`export const ${name}Schema =`)
        ) {
          throw new Error(
            `${output} declares ${rust}, which ${crate} renames to ${name}: its pack fragments are stale. ` +
              `Delete ${fragments} and run \`pnpm --filter @shift/wasm types\` again.`,
          );
        }
      }
    }
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) await writeProtocol();

// Writes src/generated-protocol/index.ts, the editor's side of shift-wasm's
// #[pack::interface] traits, and of shift-engine's StoreReader, which the
// engine asks in Rust and tests ask from TypeScript: a class per trait and
// every type they carry.
// Not committed: the build writes it before anything imports it, as it does
// the modules themselves.
//
// The pack macros write a fragment per item while they expand, which a
// `cargo check` does in seconds, but only when PACK_TS_DIR is set. The check
// uses its own target directory, so a crate that is up to date there has
// already written its fragments; a crate whose fragments are missing is
// cleaned so its macros expand again (crates/shift-bridge/scripts/types.mjs
// does the same for napi's type definitions).
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { generate } from "@shift/pack/generate";

const root = resolve(import.meta.dirname, "../../..");
const output = resolve(import.meta.dirname, "../src/generated-protocol/index.ts");
const targetDir = join(root, "target", "pack-types");
const fragments = join(targetDir, "fragments");
/** Packages with `#[derive(Pack)]` or `#[pack::interface]` items the module declares. */
const packed = ["shift-font", "shift-engine", "shift-wasm"];

const HEADER = `// Generated by packages/wasm/scripts/protocol.mjs from the #[derive(Pack)]
// and #[pack::interface] items in shift-wasm, shift-engine and shift-font. Not committed;
// \`pnpm --filter @shift/wasm types\` writes it again.
`;

/** Checks shift-wasm and shift-engine with the pack macros writing fragments, and generates the module from them. */
export function writeProtocol() {
  mkdirSync(fragments, { recursive: true });
  const cargo = (args) =>
    execFileSync("cargo", [...args, "--target-dir", targetDir], {
      cwd: root,
      stdio: "inherit",
      env: { ...process.env, PACK_TS_DIR: fragments },
    });
  const missing = packed.filter((name) => !existsSync(join(fragments, name)));
  if (missing.length > 0) cargo(["clean", ...missing.flatMap((name) => ["-p", name])]);
  cargo(["check", "-p", "shift-wasm", "-p", "shift-engine"]);
  generate(fragments, output, HEADER);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) writeProtocol();

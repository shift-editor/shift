// Builds crates/shift-wasm into src/generated: the wasm-bindgen glue and the
// module embedded as base64, so every consumer loads it synchronously with no
// bundler plugin. The output is not committed: rustc's output depends on the
// build host, so it is built like the native addon, by turbo, before anything
// that imports it. Needs the Nix dev shell's wasm-bindgen (CI:
// .github/actions/wasm-toolchain), which must match the crate version in
// Cargo.lock exactly; wasm-opt comes from the pinned binaryen devDependency.
import { execFileSync } from "node:child_process";
import { readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "../../..");
const generated = resolve(import.meta.dirname, "../src/generated");
const run = (command, args) => execFileSync(command, args, { cwd: root, stdio: "inherit" });

const locked = /name = "wasm-bindgen"\r?\nversion = "([^"]+)"/.exec(
  readFileSync(join(root, "Cargo.lock"), "utf8"),
)?.[1];
const cli = execFileSync("wasm-bindgen", ["--version"], { encoding: "utf8" }).trim().split(" ")[1];
if (locked !== cli) {
  throw new Error(`wasm-bindgen CLI ${cli} does not match ${locked} in Cargo.lock`);
}

rmSync(generated, { recursive: true, force: true });
// Paths of the checkout and the Cargo home end up in panic messages; replace
// them so the module carries no machine's paths. RUSTFLAGS replaces the target
// flags in .cargo/config.toml, so they are repeated here.
const cargoHome = process.env.CARGO_HOME ?? join(homedir(), ".cargo");
execFileSync(
  "cargo",
  ["build", "-p", "shift-wasm", "--target", "wasm32-unknown-unknown", "--release"],
  {
    cwd: root,
    stdio: "inherit",
    env: {
      ...process.env,
      RUSTFLAGS: [
        `--remap-path-prefix=${cargoHome}=/cargo`,
        `--remap-path-prefix=${root}=/shift`,
        "--cfg",
        'getrandom_backend="wasm_js"',
      ].join(" "),
    },
  },
);
run("wasm-bindgen", [
  "--target",
  "web",
  "--out-name",
  "shift_wasm",
  "--out-dir",
  generated,
  "target/wasm32-unknown-unknown/release/shift_wasm.wasm",
]);
const wasm = join(generated, "shift_wasm_bg.wasm");
// binaryen's wasm-opt is a Node script, so it runs the same on every OS.
const binaryen = createRequire(import.meta.url).resolve("binaryen/package.json");
const wasmOpt = join(dirname(binaryen), JSON.parse(readFileSync(binaryen, "utf8")).bin["wasm-opt"]);
run(process.execPath, [
  wasmOpt,
  "-Oz",
  ...[
    "bulk-memory",
    "multivalue",
    "mutable-globals",
    "nontrapping-float-to-int",
    "reference-types",
    "sign-ext",
  ].map((feature) => `--enable-${feature}`),
  wasm,
  "-o",
  wasm,
]);

// The module is embedded below; the glue's fetch-by-URL fallback would make
// bundlers emit an unused copy of it.
const glue = join(generated, "shift_wasm.js");
const fallback =
  /\r?\n\s*module_or_path = new URL\('shift_wasm_bg\.wasm', import\.meta\.url\);(\r?\n)/;
const source = readFileSync(glue, "utf8");
if (!fallback.test(source)) {
  throw new Error("wasm-bindgen glue no longer has the fetch-by-URL fallback this script removes");
}
writeFileSync(glue, source.replace(fallback, "$1"));
writeFileSync(
  join(generated, "module.ts"),
  `// Generated by packages/wasm/scripts/build.mjs from crates/shift-wasm; do not edit.\n` +
    `export const moduleBase64 = "${readFileSync(wasm).toString("base64")}";\n`,
);
rmSync(wasm);
rmSync(join(generated, "shift_wasm_bg.wasm.d.ts"), { force: true });
rmSync(join(generated, ".gitignore"), { force: true });

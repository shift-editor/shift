// Builds crates/shift-wasm into src/generated: the wasm-bindgen glue and the
// module embedded as base64, so every consumer loads it synchronously with no
// bundler plugin. `--check` rebuilds into a temporary folder and fails when
// the committed output differs. Needs the Nix dev shell's wasm-bindgen and
// wasm-opt; wasm-bindgen must match the crate version in Cargo.lock exactly.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync, readdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "../../..");
const generated = resolve(import.meta.dirname, "../src/generated");
const check = process.argv.includes("--check");
const run = (command, args) => execFileSync(command, args, { cwd: root, stdio: "inherit" });

const locked = /name = "wasm-bindgen"\nversion = "([^"]+)"/.exec(
  readFileSync(join(root, "Cargo.lock"), "utf8"),
)?.[1];
const cli = execFileSync("wasm-bindgen", ["--version"], { encoding: "utf8" }).trim().split(" ")[1];
if (locked !== cli) {
  throw new Error(`wasm-bindgen CLI ${cli} does not match ${locked} in Cargo.lock`);
}

const out = check ? mkdtempSync(join(tmpdir(), "shift-wasm-")) : generated;
run("cargo", ["build", "-p", "shift-wasm", "--target", "wasm32-unknown-unknown", "--release"]);
run("wasm-bindgen", [
  "--target",
  "web",
  "--out-name",
  "shift_wasm",
  "--out-dir",
  out,
  "target/wasm32-unknown-unknown/release/shift_wasm.wasm",
]);
const wasm = join(out, "shift_wasm_bg.wasm");
run("wasm-opt", [
  "-Oz",
  ...[
    "bulk-memory",
    "multivalue",
    "mutable-globals",
    "nontrapping-float-to-int",
    "reference-types",
    "sign-ext",
  ].map((feature) => `--enable-${feature}`),
  wasm,
  "-o",
  wasm,
]);

// The module is embedded below; the glue's fetch-by-URL fallback would make
// bundlers emit an unused copy of it.
const glue = join(out, "shift_wasm.js");
writeFileSync(
  glue,
  readFileSync(glue, "utf8").replace(
    /\n\s*module_or_path = new URL\('shift_wasm_bg\.wasm', import\.meta\.url\);\n/,
    "\n",
  ),
);
writeFileSync(
  join(out, "module.ts"),
  `// Generated by packages/wasm/scripts/build.mjs from crates/shift-wasm; do not edit.\n` +
    `export const moduleBase64 = "${readFileSync(wasm).toString("base64")}";\n`,
);
rmSync(wasm);
rmSync(join(out, "shift_wasm_bg.wasm.d.ts"), { force: true });
rmSync(join(out, ".gitignore"), { force: true });

if (check) {
  const differs = readdirSync(out).filter(
    (file) => readFileSync(join(out, file), "utf8") !== readFileSync(join(generated, file), "utf8"),
  );
  rmSync(out, { recursive: true });
  if (differs.length > 0) {
    throw new Error(
      `packages/wasm/src/generated is stale (${differs.join(", ")}); run pnpm --filter @shift/wasm build:wasm`,
    );
  }
}

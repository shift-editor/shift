import { describe, expect, it } from "vitest";
import type { Bounds, MatModel } from "@shift/geo";
import type { GlyphState, GlyphStructure, LayerId } from "@shift/types";
import { angleBetween } from "@shift/glyph-state/testing";
import reference from "@shift/types/fixtures/geometry_reference.json";
import { LayerBuffers } from "./LayerBuffers";

interface LayerTransformCase {
  readonly name: string;
  readonly matrix: MatModel;
  readonly after: number[];
  readonly afterBounds: Bounds | null;
}

interface LayerInput {
  readonly layerId: string;
  readonly structure: GlyphStructure;
  readonly values: number[];
}

// Generated by `crates/shift-wire/tests/geometry_reference.rs`. Every case
// transforms the same `layerInput`.
const layerInput = reference.layerInput as unknown as LayerInput;
const layerCases = reference.layerTransforms as unknown as LayerTransformCase[];

const DIGITS = 9;
const COMPONENT_VALUES = 9;
const COMPONENT_ROTATION = 2;

function inputLayer(): LayerBuffers {
  const state: GlyphState = {
    layerId: layerInput.layerId as LayerId,
    structure: layerInput.structure,
    values: new Float64Array(layerInput.values),
  };

  return LayerBuffers.fromState(state);
}

/** Indices of each component's rotation in a layer's packed values. */
function rotationSlots(structure: GlyphStructure, valueCount: number): Set<number> {
  const componentStart = valueCount - structure.components.length * COMPONENT_VALUES;

  return new Set(
    structure.components.map(
      (_, index) => componentStart + index * COMPONENT_VALUES + COMPONENT_ROTATION,
    ),
  );
}

describe("whole-layer transforms match shift-font's transform_layer", () => {
  it.each(layerCases)("transforms points, anchors, and components for $name", (testCase) => {
    const layer = inputLayer();
    const rotations = rotationSlots(layerInput.structure, testCase.after.length);

    layer.transformLayer(testCase.matrix);

    const actual = [...layer.snapshot];
    expect(actual).toHaveLength(testCase.after.length);
    testCase.after.forEach((expected, index) => {
      const difference = rotations.has(index)
        ? angleBetween(actual[index]!, expected)
        : actual[index]! - expected;
      expect(difference, `value ${index}`).toBeCloseTo(0, DIGITS);
    });
  });

  it.each(layerCases)("bounds the layer after $name like layer_bbox", (testCase) => {
    const layer = inputLayer();

    layer.transformLayer(testCase.matrix);

    const bounds = layer.bounds;
    const expected = testCase.afterBounds!;
    expect(bounds).not.toBeNull();
    expect(bounds!.min.x).toBeCloseTo(expected.min.x, DIGITS);
    expect(bounds!.min.y).toBeCloseTo(expected.min.y, DIGITS);
    expect(bounds!.max.x).toBeCloseTo(expected.max.x, DIGITS);
    expect(bounds!.max.y).toBeCloseTo(expected.max.y, DIGITS);
  });
});

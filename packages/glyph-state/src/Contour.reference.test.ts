import { describe, expect, it } from "vitest";
import type { Bounds } from "@shift/geo";
import { asContourId, asPointId, type PointType } from "@shift/types";
import reference from "@shift/types/fixtures/geometry_reference.json";
import { Contour } from "./Contour";

interface ReferenceSegment {
  readonly type: "line" | "quad" | "cubic";
  readonly points: number[];
  readonly bounds: Bounds;
}

interface ContourCase {
  readonly name: string;
  readonly closed: boolean;
  readonly points: { readonly x: number; readonly y: number; readonly pointType: PointType }[];
  readonly segments: ReferenceSegment[];
  readonly bounds: Bounds | null;
}

// Generated by `crates/shift-wire/tests/geometry_reference.rs`.
const contourCases = reference.contours as ContourCase[];

const DIGITS = 9;

function contourFor(testCase: ContourCase): Contour {
  const data = {
    id: asContourId("reference"),
    closed: testCase.closed,
    points: testCase.points.map((point, index) => ({
      id: asPointId(`p${index}`),
      pointType: point.pointType,
      smooth: false,
    })),
  };
  const values = new Float64Array(testCase.points.flatMap((point) => [point.x, point.y]));

  return new Contour(data, values, 0);
}

function expectBounds(actual: Bounds | null, expected: Bounds | null): void {
  if (expected === null) {
    expect(actual).toBeNull();
    return;
  }

  expect(actual).not.toBeNull();
  expect(actual!.min.x).toBeCloseTo(expected.min.x, DIGITS);
  expect(actual!.min.y).toBeCloseTo(expected.min.y, DIGITS);
  expect(actual!.max.x).toBeCloseTo(expected.max.x, DIGITS);
  expect(actual!.max.y).toBeCloseTo(expected.max.y, DIGITS);
}

describe("contour segments and bounds match shift-font's CurveSegmentIter", () => {
  it.each(contourCases)("parses $name into the same segments", (testCase) => {
    const contour = contourFor(testCase);
    const segments = contour.segments().map((segment) => ({
      type: segment.type,
      points: segment.flatPoints.map((point) => contour.points.indexOf(point)),
    }));

    expect(segments).toEqual(testCase.segments.map(({ type, points }) => ({ type, points })));
  });

  it.each(contourCases)("bounds each segment of $name like segment_bounds", (testCase) => {
    const segments = contourFor(testCase).segments();

    expect(segments).toHaveLength(testCase.segments.length);
    segments.forEach((segment, index) => {
      expectBounds(segment.bounds, testCase.segments[index]!.bounds);
    });
  });

  it.each(contourCases)("bounds $name like resolved_contours_bbox", (testCase) => {
    expectBounds(contourFor(testCase).bounds, testCase.bounds);
  });
});
